#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildExportedTypeIndex,
  createKitProgram,
  extractProps,
  parseDocsTags,
  readMeta,
  resolvePropsDeclaration,
} from "./lib/props-gen.mjs";

const demoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(demoRoot, "..", "..");
const kitSrcDir = path.join(repoRoot, "packages", "ui-kit", "src");
const contentDir = path.join(demoRoot, "src", "content", "components");
const outputFile = path.join(contentDir, "props-map.ts");
const check = process.argv.includes("--check");

const { program, checker } = createKitProgram(kitSrcDir);
const typeIndex = buildExportedTypeIndex(program);

const slugs = fs
  .readdirSync(contentDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const propsMap = {};
const skipped = [];
const missing = [];

for (const slug of slugs) {
  const metaFile = path.join(contentDir, slug, "meta.ts");
  if (!fs.existsSync(metaFile)) continue;
  const meta = readMeta(metaFile);
  if (Array.isArray(meta.manualProps)) {
    skipped.push(slug);
    continue;
  }

  const resolved = resolvePropsDeclaration(typeIndex, slug);
  if (!resolved) {
    missing.push(slug);
    propsMap[slug] = [];
    continue;
  }

  const docsTags = parseDocsTags(resolved.node);
  if (docsTags.size) {
    const type = checker.getTypeAtLocation(resolved.node.name);
    const propNames = new Set(checker.getPropertiesOfType(type).map((symbol) => symbol.getName()));
    for (const name of docsTags.keys()) {
      if (!propNames.has(name)) {
        console.warn(`Warning: ${resolved.typeName} has docs for unknown prop "${name}" (${slug}).`);
      }
    }
  }

  const props = extractProps({
    program,
    checker,
    kitSrcDir,
    decl: resolved.node,
  });

  if (props.length === 0) {
    console.warn(`Warning: no documented props found for "${slug}" (${resolved.typeName}).`);
  }

  propsMap[slug] = props;
}

if (missing.length) {
  console.warn(`No exported props type found for: ${missing.join(", ")}`);
  console.warn(
    "These components get an empty props table until a *Props type is added or manualProps is set in meta.ts.",
  );
}

const source = `// Generated by scripts/gen-props.mjs — do not edit by hand.
// Source of truth: JSDoc on exported *Props types in packages/ui-kit/src.
import type { ComponentProp } from "@/content/types";

export const propsMap: Record<string, ComponentProp[]> = ${JSON.stringify(propsMap, null, 2)};
`;

const current = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, "utf8") : "";
if (current !== source) {
  if (check) {
    console.error("Out of date: src/content/components/props-map.ts");
    console.error("Run `npm run gen:props` to regenerate it.");
    process.exit(1);
  }
  fs.writeFileSync(outputFile, source);
  console.log(`Updated src/content/components/props-map.ts (${Object.keys(propsMap).length} components).`);
} else {
  console.log(`Props map is up to date (${Object.keys(propsMap).length} components).`);
}

if (skipped.length) {
  console.log(`Manual props: ${skipped.join(", ")}`);
}
